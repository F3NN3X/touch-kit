<#
.SYNOPSIS
  Give a touch panel back to Windows: undo a Zadig/libwdi WinUSB install for one VID/PID.
  Run elevated by the panel app (one UAC prompt); the app asks the user to confirm first.
.DESCRIPTION
  No prompts; also removes the certificate libwdi leaves behind. Usable from a shell too (elevated):
  1. Finds the USB node(s) for VID/PID bound to WinUSB.
  2. Deletes the bound driver package only if it is an oem*.inf that names this VID/PID
     (never a shared package), and removes the device node.
  3. Removes the "CN=USB\VID_xxxx&PID_xxxx (libwdi autogenerated)" certificate for this VID/PID
     from LocalMachine Root and TrustedPublisher. libwdi adds one per install and never removes it.
  4. Rescans hardware: Windows rebinds its inbox HID driver.
  Exit codes: 0 done, 2 nothing bound to WinUSB (certificate still removed), 1 failed.
#>
param(
  [Parameter(Mandatory)] [ValidatePattern('^[0-9A-Fa-f]{4}$')] [string]$Vid,
  [Parameter(Mandatory)] [ValidatePattern('^[0-9A-Fa-f]{4}$')] [string]$ProductId,
  [Parameter(Mandatory)] [string]$Log
)
$ErrorActionPreference = 'Stop'
Start-Transcript -Path $Log -Force | Out-Null
$code = 0
try {
  $isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).
    IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
  if (-not $isAdmin) { throw 'not elevated' }

  $pattern = "VID_$Vid&PID_$ProductId"
  $targets = Get-PnpDevice -ErrorAction SilentlyContinue |
    Where-Object { $_.InstanceId -like "USB\$pattern*" } |
    ForEach-Object {
      $svc = (Get-PnpDeviceProperty -InstanceId $_.InstanceId -KeyName 'DEVPKEY_Device_Service' -ErrorAction SilentlyContinue).Data
      $inf = (Get-PnpDeviceProperty -InstanceId $_.InstanceId -KeyName 'DEVPKEY_Device_DriverInfPath' -ErrorAction SilentlyContinue).Data
      [pscustomobject]@{ InstanceId = $_.InstanceId; Service = $svc; Inf = $inf }
    } |
    Where-Object { $_.Service -eq 'WinUSB' }

  if (-not $targets) {
    Write-Output "No $pattern node is bound to WinUSB."
    $code = 2
  }
  foreach ($t in $targets) {
    Write-Output "Device: $($t.InstanceId)  INF: $($t.Inf)"
    $deleteInf = $false
    if ($t.Inf -and $t.Inf -like 'oem*.inf') {
      $infPath = Join-Path $env:WINDIR "INF\$($t.Inf)"
      if ((Test-Path $infPath) -and (Select-String -Path $infPath -Pattern $pattern -SimpleMatch -Quiet)) {
        $deleteInf = $true
      } else {
        Write-Output "$($t.Inf) does not mention $pattern; leaving that driver package in place (it may be shared)."
      }
    }
    pnputil /remove-device "$($t.InstanceId)" | Write-Output
    if ($LASTEXITCODE -ne 0) { throw "pnputil /remove-device failed ($LASTEXITCODE)" }
    if ($deleteInf) {
      pnputil /delete-driver $t.Inf /uninstall /force | Write-Output
      if ($LASTEXITCODE -ne 0) { throw "pnputil /delete-driver $($t.Inf) failed ($LASTEXITCODE)" }
    }
  }

  $subject = "CN=USB\$pattern (libwdi autogenerated)"
  foreach ($store in 'Root', 'TrustedPublisher') {
    Get-ChildItem "Cert:\LocalMachine\$store" | Where-Object { $_.Subject -eq $subject } | ForEach-Object {
      Write-Output "Removing certificate $($_.Thumbprint) from LocalMachine\$store"
      Remove-Item -Path $_.PSPath
    }
  }

  pnputil /scan-devices | Write-Output
  Write-Output 'Done.'
} catch {
  Write-Output "FAILED: $($_.Exception.Message)"
  $code = 1
} finally {
  Stop-Transcript | Out-Null
}
exit $code
